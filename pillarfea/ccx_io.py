"""CalculiX input writing, execution and result parsing.

Conventions verified in validation:
- axisymmetric (CAX*) reaction forces in the .dat file refer to a 2-degree segment, so the
  full-ring force is 180 x the printed value;
- with NLGEOM, *PLASTIC is the finite-strain (multiplicative) J2 model; the printed stress
  is Cauchy stress.
"""
from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

import numpy as np

from .geometry import Mesh, edge_faces
from .materials import Material

AXI_FORCE_FACTOR = 180.0


def _chunks(ids, n=12):
    ids = list(ids)
    for i in range(0, len(ids), n):
        yield ", ".join(str(int(x) + 1) for x in ids[i:i + n]) + ","


def write_inp(path: Path, mesh: Mesh, pillar: Material, substrate: Material | None,
              contact: dict, delta_max: float, n_inc: int,
              linear_solver: str = "spooles") -> str:
    """Write the CalculiX deck; returns the name of the node set carrying the punch force.

    contact['top']:
      frictionless  top face: u_z prescribed, u_r free           (exact, no contact algorithm)
      bonded        top face: u_z prescribed, u_r = 0            (exact, no contact algorithm)
      coulomb       stiff elastic punch block (E = punch_E_factor * E, nu = 0) driven on its
                    top face (u_z prescribed, u_r = 0); surface-to-surface penalty contact,
                    slave = pillar top, master = punch bottom; Coulomb friction mu with stick
                    slope lambda (mu = 0: frictionless contact algorithm, no *FRICTION).
    """
    mode = contact["top"]
    L = ["** generated by pillarfea", "*NODE, NSET=NALL"]
    L += [f"{i + 1}, {r:.12g}, {z:.12g}" for i, (r, z) in enumerate(mesh.nodes)]
    for name, eids in mesh.elsets.items():
        L.append(f"*ELEMENT, TYPE=CAX8R, ELSET={name}")
        L += [f"{e + 1}, " + ", ".join(str(n + 1) for n in mesh.elements[e]) for e in eids]
    for name, nids in mesh.nsets.items():
        L.append(f"*NSET, NSET={name}")
        L += list(_chunks(nids))
    L += pillar.ccx_lines("PILLARMAT")
    L.append("*SOLID SECTION, ELSET=PILLAR, MATERIAL=PILLARMAT")
    if substrate is not None:
        L += substrate.ccx_lines("SUBMAT")
        L.append("*SOLID SECTION, ELSET=SUBST, MATERIAL=SUBMAT")
    force_set = "TOP"
    if mode == "coulomb":
        if "PUNCH" not in mesh.elsets:
            raise ValueError("Coulomb contact needs a mesh built with the punch block")
        force_set = "PTOP"
        L += ["*MATERIAL, NAME=PUNCHMAT", "*ELASTIC",
              f"{float(contact['punch_E_factor']) * pillar.E:.10g}, 0.0",
              "*SOLID SECTION, ELSET=PUNCH, MATERIAL=PUNCHMAT"]
        L.append("*SURFACE, NAME=SPILLAR, TYPE=ELEMENT")
        L += [f"{e + 1}, S{f}" for e, f in edge_faces(mesh, "PILLAR", "TOP")]
        L.append("*SURFACE, NAME=SPUNCH, TYPE=ELEMENT")
        L += [f"{e + 1}, S{f}" for e, f in edge_faces(mesh, "PUNCH", "PBOT")]
        r_top = np.unique(np.round(mesh.nodes[mesh.nsets["TOP"], 0], 12))
        h_min = float(np.min(np.diff(r_top)))     # smallest node spacing on the top face
        K = float(contact["penalty_factor"]) * pillar.E / h_min
        L += ["*CONTACT PAIR, INTERACTION=SI1, TYPE=SURFACE TO SURFACE", "SPILLAR, SPUNCH",
              "*SURFACE INTERACTION, NAME=SI1",
              "*SURFACE BEHAVIOR, PRESSURE-OVERCLOSURE=LINEAR", f"{K:.10g}"]
        mu = float(contact["mu"])
        if mu > 0:
            L += ["*FRICTION", f"{mu:.10g}, {float(contact['stick_ratio']) * K:.10g}"]
    elif mode not in ("frictionless", "bonded"):
        raise ValueError(f"Unknown contact mode '{mode}'")
    L += ["*BOUNDARY", "AXIS, 1, 1, 0."]
    support = "OUTER" if substrate is not None else "PBASE"
    L.append("OUTER, 1, 2, 0." if substrate is not None else "PBASE, 2, 2, 0.")
    dt = 1.0 / n_inc
    static = "*STATIC" if linear_solver in (None, "", "default") else \
        f"*STATIC, SOLVER={linear_solver.upper()}"
    dtmin = max(dt * 1e-3, 2e-6)   # ccx raises anything below 1e-6 x step time anyway
    L += ["*STEP, NLGEOM, INC=100000", static, f"{dt:.10g}, 1.0, {dtmin:.10g}, {dt:.10g}",
          "*BOUNDARY", f"{force_set}, 2, 2, {-delta_max:.12g}"]
    if mode in ("bonded", "coulomb"):
        L.append(f"{force_set}, 1, 1, 0.")
    L += [f"*NODE PRINT, NSET={force_set}, TOTALS=ONLY, FREQUENCY=1", "RF",
          f"*NODE PRINT, NSET={support}, TOTALS=ONLY, FREQUENCY=1", "RF",
          "*NODE PRINT, NSET=TOPREF, FREQUENCY=1", "U"]
    if mode != "coulomb":   # per-node punch forces on the top face (lift-off check)
        L += ["*NODE PRINT, NSET=TOP, FREQUENCY=1", "RF"]
    if substrate is not None:
        L += ["*NODE PRINT, NSET=PBASE, FREQUENCY=1", "U"]
    # NB: in ccx the output frequency is shared between .dat and .frd, so fields are written
    # every increment and pruned to n_frames after the run (see parse_frd).
    L += ["*NODE FILE", "U", "*EL FILE", "S, PEEQ", "*END STEP"]
    path.write_text("\n".join(L) + "\n")
    return force_set


class CcxError(RuntimeError):
    """CalculiX reported an error itself (input, convergence): not retried."""


class CcxCrash(RuntimeError):
    """CalculiX terminated without its own error message (e.g. access violation)."""


def run_ccx(workdir: Path, exe: str, job: str = "job", threads: int = 1,
            timeout: float = 3600, max_attempts: int = 3) -> int:
    """Run CalculiX; repeat from scratch if the process crashes. Returns attempts used.

    A crash (non-zero exit without a CalculiX '*ERROR' message) is retried because the
    MSYS2 ARM64 build crashes intermittently (access violation, ~1 in 3 runs, at varying
    increments) on identical input; completed runs agree with the x64 build to all digits.
    Genuine CalculiX errors are raised immediately.
    """
    env = dict(os.environ)
    env["OMP_NUM_THREADS"] = str(threads)
    env["CCX_NPROC_STIFFNESS"] = str(threads)
    env["CCX_NPROC_EQUATION_SOLVER"] = str(threads)
    log_path = workdir / "ccx.log"
    for attempt in range(1, max(1, int(max_attempts)) + 1):
        for ext in (".dat", ".sta", ".frd", ".cvg", ".12d"):
            (workdir / (job + ext)).unlink(missing_ok=True)
        with open(log_path, "w") as log:
            p = subprocess.run([exe, "-i", job], cwd=workdir, stdout=log,
                               stderr=subprocess.STDOUT, env=env, timeout=timeout,
                               creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        text = log_path.read_text(errors="replace")
        if p.returncode == 0 and "*ERROR" not in text and "Job finished" in text:
            if attempt > 1:
                with open(workdir / "crashes.log", "a") as f:
                    f.write(f"succeeded on attempt {attempt}\n")
            return attempt
        tail = "\n".join(text.splitlines()[-25:])
        if "*ERROR" in text:
            raise CcxError(f"CalculiX error in {workdir} (code {p.returncode}):\n{tail}")
        with open(workdir / "crashes.log", "a") as f:
            f.write(f"attempt {attempt}: exit code 0x{p.returncode & 0xFFFFFFFF:08X}\n")
    raise CcxCrash(f"CalculiX crashed {max_attempts} times in {workdir} "
                   f"(last exit code 0x{p.returncode & 0xFFFFFFFF:08X}):\n{tail}")


_HDR = re.compile(r"^\s*(total force|displacements|forces)\s*\(.*?\)\s*for set\s+(\S+)"
                  r"\s+and time\s+(\S+)")


def parse_dat(path: Path) -> dict:
    """Return {(kind, set): {time: data}}; data is a 3-vector (totals) or {node: 3-vector}."""
    out: dict = {}
    cur = None
    for line in Path(path).read_text(errors="replace").splitlines():
        m = _HDR.match(line)
        if m:
            kind = {"total force": "RF", "forces": "RFN", "displacements": "U"}[m.group(1)]
            cur = (kind, m.group(2).upper(), float(m.group(3)))
            out.setdefault(cur[:2], {})[cur[2]] = None if kind == "RF" else {}
            continue
        if cur is None or not line.strip():
            continue
        vals = line.split()
        try:
            nums = [float(v) for v in vals]
        except ValueError:
            cur = None
            continue
        store = out[cur[:2]]
        if cur[0] == "RF" and len(nums) == 3:
            store[cur[2]] = np.array(nums)
        elif cur[0] in ("U", "RFN") and len(nums) == 4:
            store[cur[2]][int(nums[0])] = np.array(nums[1:])
    return out


def _number_regex(sample: str) -> re.Pattern:
    """Values in frd lines are glued together (E12.5). Windows (MinGW) builds print 3-digit
    exponents, so negative values overflow the field; detect the exponent width instead of
    relying on fixed columns."""
    for nd in (3, 2):
        pat = re.compile(rf"[-+ ]?\d\.\d+E[+-]\d{{{nd}}}")
        if pat.sub("", sample).strip() == "" and pat.findall(sample):
            return pat
    raise ValueError(f"Unrecognised frd number format: {sample!r}")


def parse_frd(path: Path, n_nodes: int, keep_times=None) -> dict:
    """Nodal result frames at the requested times (all if None).

    Returns {'time': (K,), 'U': (K,N,2), 'S': (K,N,4) [srr, szz, stt, srz], 'PEEQ': (K,N)}
    as float32. Fixed-width frd format: ' -1' + I10 node id + E12.5 values;
    '  100C' header carries the step time in columns 12-24.
    """
    want = None if keep_times is None else np.asarray(keep_times, float)
    frames: dict[float, dict] = {}
    cur = block = None
    num = None
    with open(path, errors="replace") as fh:
        for line in fh:
            if num is None and line.startswith(" -1"):
                num = _number_regex(line[13:].rstrip())
            if line.startswith("  100C"):
                t = float(line[12:24])
                if want is None or np.min(np.abs(want - t)) < 1e-7:
                    cur = frames.setdefault(t, {})
                else:
                    cur = None
                block = None
                continue
            if cur is None:
                continue
            if line.startswith(" -4"):
                name = line.split()[1]
                block = name if name in ("DISP", "STRESS", "PE") else None
                if block:
                    cur[block] = np.full((n_nodes, 6), np.nan, dtype=np.float32)
                continue
            if block and line.startswith(" -1"):
                nid = int(line[3:13])
                if 1 <= nid <= n_nodes:
                    vals = num.findall(line, 13)
                    cur[block][nid - 1, :len(vals)] = [float(v) for v in vals[:6]]
            elif line.startswith(" -3"):
                block = None
    ts = sorted(frames)
    out = {"time": np.array(ts)}
    out["U"] = np.stack([frames[t]["DISP"][:, :2] for t in ts])
    out["S"] = np.stack([frames[t]["STRESS"][:, [0, 1, 2, 3]] for t in ts])  # xx, yy, zz, xy
    out["PEEQ"] = np.stack([frames[t]["PE"][:, 0] if "PE" in frames[t]
                            else np.zeros(n_nodes, np.float32) for t in ts])
    return out


def von_mises(S: np.ndarray) -> np.ndarray:
    """S[..., 4] = (s_rr, s_zz, s_tt, s_rz) -> von Mises stress."""
    a, b, c, d = S[..., 0], S[..., 1], S[..., 2], S[..., 3]
    return np.sqrt(0.5 * ((a - b) ** 2 + (b - c) ** 2 + (c - a) ** 2) + 3.0 * d ** 2)
